#!/usr/bin/env node
/**
 * Generate MP3 files for all TEF lexique terms using OpenAI TTS API.
 * Run once: node scripts/generate-lexique-audio.mjs
 * 
 * Output: public/audio/lexique/<slug>.mp3
 * Uses voice "nova" (best French pronunciation) at speed 0.9
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

// Read API key from .env.local
const envPath = path.join(ROOT, '.env.local');
const envContent = fs.readFileSync(envPath, 'utf-8');
const apiKeyMatch = envContent.match(/OPENAI_API_KEY=(.+)/);
if (!apiKeyMatch) { console.error('No OPENAI_API_KEY in .env.local'); process.exit(1); }
const API_KEY = apiKeyMatch[1].trim();

const OUTPUT_DIR = path.join(ROOT, 'public', 'audio', 'lexique');
fs.mkdirSync(OUTPUT_DIR, { recursive: true });

// All lexique terms — extracted from tef-lexique-data.ts
// We'll parse the file to get them automatically
const lexiqueDataPath = path.join(ROOT, 'src', 'components', 'tef', 'tef-lexique-data.ts');
const lexiqueContent = fs.readFileSync(lexiqueDataPath, 'utf-8');

// Extract all term values using regex  
// The file uses both single and double quotes: term: 'xxx' or term: "l'appartement"
const terms = [];
const termRegex = /term:\s*(['"])(.*?)\1/g;
let match;
while ((match = termRegex.exec(lexiqueContent)) !== null) {
  terms.push(match[2]);
}

// Deduplicate while preserving order
const uniqueTerms = [...new Set(terms)];

console.log(`Found ${uniqueTerms.length} unique terms to generate audio for.`);

// Slugify a term for filename — handles French apostrophes correctly
// "l'appartement" → "l-appartement" (not "l")
// "s'adapter" → "s-adapter" (not "s")
function slugify(term) {
  return term
    .toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '') // remove diacritics
    .replace(/[''\u2019]/g, '-')  // apostrophes → dash (BEFORE the general cleanup)
    .replace(/[^a-z0-9-]+/g, '-') // non-alphanumeric → dash
    .replace(/-{2,}/g, '-')       // collapse multiple dashes
    .replace(/^-+|-+$/g, '');     // trim leading/trailing dashes
}

// Generate TTS for a single term
async function generateAudio(term, slug) {
  const outPath = path.join(OUTPUT_DIR, `${slug}.mp3`);
  
  // Skip if already generated
  if (fs.existsSync(outPath)) {
    const stat = fs.statSync(outPath);
    if (stat.size > 1000) {
      console.log(`  SKIP ${slug} (already exists, ${stat.size}B)`);
      return true;
    }
    // Remove corrupted file
    fs.unlinkSync(outPath);
  }

  try {
    const response = await fetch('https://api.openai.com/v1/audio/speech', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${API_KEY}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: 'tts-1',
        input: term,
        voice: 'nova',
        speed: 0.9,
        response_format: 'mp3',
      }),
    });

    if (!response.ok) {
      const err = await response.text();
      console.error(`  FAIL ${slug}: ${response.status} ${err}`);
      return false;
    }

    const buffer = Buffer.from(await response.arrayBuffer());
    fs.writeFileSync(outPath, buffer);
    console.log(`  OK   ${slug} (${buffer.length}B) - "${term}"`);
    return true;
  } catch (err) {
    console.error(`  ERR  ${slug}: ${err.message}`);
    return false;
  }
}

// Also generate a mapping file for use in the app
async function generateMapping(terms) {
  const mapping = {};
  for (const term of terms) {
    const slug = slugify(term);
    mapping[term] = `/audio/lexique/${slug}.mp3`;
  }
  
  const mapPath = path.join(ROOT, 'src', 'components', 'tef', 'tef-lexique-audio-map.ts');
  const content = `// Auto-generated by scripts/generate-lexique-audio.mjs
// Maps lexique terms to their pre-generated MP3 file paths
// DO NOT EDIT MANUALLY

export const lexiqueAudioMap: Record<string, string> = ${JSON.stringify(mapping, null, 2)};

export function getAudioUrl(term: string): string | null {
  return lexiqueAudioMap[term] ?? null;
}
`;
  fs.writeFileSync(mapPath, content);
  console.log(`\nMapping file written: ${mapPath}`);
}

// Main
async function main() {
  console.log(`\nGenerating ${uniqueTerms.length} MP3 files...\n`);
  
  // Check for slug collisions before generating
  const slugMap = new Map();
  for (const term of uniqueTerms) {
    const slug = slugify(term);
    if (slugMap.has(slug)) {
      console.warn(`  COLLISION: "${term}" and "${slugMap.get(slug)}" both slugify to "${slug}"`);
    }
    slugMap.set(slug, term);
  }
  
  let success = 0;
  let fail = 0;
  
  // Process in batches of 5 to avoid rate limiting
  const BATCH_SIZE = 5;
  for (let i = 0; i < uniqueTerms.length; i += BATCH_SIZE) {
    const batch = uniqueTerms.slice(i, i + BATCH_SIZE);
    const results = await Promise.all(
      batch.map(term => generateAudio(term, slugify(term)))
    );
    
    for (const r of results) {
      if (r) success++; else fail++;
    }
    
    // Small delay between batches
    if (i + BATCH_SIZE < uniqueTerms.length) {
      await new Promise(r => setTimeout(r, 200));
    }
    
    // Progress
    const done = Math.min(i + BATCH_SIZE, uniqueTerms.length);
    process.stdout.write(`\r  Progress: ${done}/${uniqueTerms.length} (${Math.round(done/uniqueTerms.length*100)}%)`);
  }
  
  console.log(`\n\nDone! ${success} success, ${fail} failures.`);
  
  // Generate the mapping file
  await generateMapping(uniqueTerms);
  
  // Show total size
  let totalSize = 0;
  const files = fs.readdirSync(OUTPUT_DIR);
  for (const f of files) {
    totalSize += fs.statSync(path.join(OUTPUT_DIR, f)).size;
  }
  console.log(`Total audio size: ${(totalSize / 1024 / 1024).toFixed(2)} MB (${files.length} files)`);
}

main().catch(console.error);
