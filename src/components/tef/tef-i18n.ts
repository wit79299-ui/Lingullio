// ── Hook: useTefLocale ──
export function useTefLocale() {
  const locale = useLocale();
  const tefLocale: TefLocale = locale === 'fr' ? 'fr' : 'en';
  const dict = dictionaries[tefLocale];

  function t(key: string, params?: Record<string, string | number>): string {
    let value = dict[key] ?? dictionaries['fr'][key] ?? key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        value = value.replace(`{${k}}`, String(v));
      });
    }
    return value;
  }

  /** Translate a trap explanation from tef-data.ts */
  function tExp(frenchText: string): string {
    if (tefLocale === 'fr') return frenchText;
    return trapExplanationsEN[frenchText] ?? frenchText;
  }

  /** Translate a trap section title */
  function tTrapTitle(frenchTitle: string): string {
    if (tefLocale === 'fr') return frenchTitle;
    return trapSectionTitlesEN[frenchTitle] ?? frenchTitle;
  }

  /** Translate a trap name */
  function tTrapName(frenchName: string): string {
    if (tefLocale === 'fr') return frenchName;
    return trapNamesEN[frenchName] ?? frenchName;
  }

  return { t, tExp, tTrapName, tTrapTitle, locale: tefLocale };
}
